"""Generate Python gRPC stubs from proto/rag.proto into rag_service/pb/.

    python scripts/gen_proto.py

CI re-runs this and fails if the committed stubs differ (stale stubs = silent contract drift).
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

from grpc_tools import protoc

ROOT = Path(__file__).resolve().parent.parent
PROTO_DIR = ROOT / "proto"
OUT_DIR = ROOT / "rag_service" / "pb"


def main() -> int:
    OUT_DIR.mkdir(exist_ok=True)
    (OUT_DIR / "__init__.py").write_text('"""Generated by scripts/gen_proto.py. Do not edit."""\n')
    include = Path(protoc.__file__).parent / "_proto"  # google/protobuf well-known types
    rc = protoc.main(
        [
            "grpc_tools.protoc",
            f"-I{PROTO_DIR}",
            f"-I{include}",
            f"--python_out={OUT_DIR}",
            f"--pyi_out={OUT_DIR}",
            f"--grpc_python_out={OUT_DIR}",
            str(PROTO_DIR / "rag.proto"),
        ]
    )
    if rc != 0:
        return rc
    # protoc emits `import rag_pb2`, which only works if pb/ is on sys.path; make it relative.
    grpc_file = OUT_DIR / "rag_pb2_grpc.py"
    src = grpc_file.read_text(encoding="utf-8")
    grpc_file.write_text(
        re.sub(r"^import rag_pb2 as", "from . import rag_pb2 as", src, flags=re.M),
        encoding="utf-8",
        newline="\n",
    )
    print(f"generated stubs in {OUT_DIR.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
